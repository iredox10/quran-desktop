package com.nur.quran.desktop.data

import com.google.gson.Gson
import com.google.gson.annotations.SerializedName
import java.io.File
import java.net.HttpURLConnection
import java.net.URL

/** One word of a mushaf page: display text + Madani line number. */
data class PageWord(
    val verseKey: String,
    val text: String,
    val lineNumber: Int,
    val translation: String = ""
)

/** One bundled word of a verse, used by the reader's word tooltips. */
data class VerseWord(
    val verseKey: String,
    val position: Int,
    val arabic: String,
    val translation: String,
    val transliteration: String,
    val tajweedHtml: String,
    val isEndMarker: Boolean
)

/** Private JSON models for `GET /verses/by_page/{page}` (only fields used). */
private data class PageWordsResponse(
    val verses: List<PageVerseJson>? = null
)

private data class PageVerseJson(
    @SerializedName("verse_key") val verseKey: String = "",
    val words: List<PageWordJson>? = null
)

private data class PageTranslationJson(val text: String? = null)

private data class PageWordJson(
    @SerializedName("text_uthmani") val textUthmani: String? = null,
    @SerializedName("text_qpc_hafs") val textQpcHafs: String? = null,
    @SerializedName("text_indopak") val textIndopak: String? = null,
    @SerializedName("line_number") val lineNumber: Int? = null,
    val translation: PageTranslationJson? = null
)

/** Private JSON models for the bundled `data/words/{chapter}.json` files. */
private data class BundledVerseJson(
    @SerializedName("k") val key: String = "",
    @SerializedName("w") val words: List<BundledWordJson>? = null
)

private data class BundledWordJson(
    @SerializedName("a") val arabic: String = "",
    @SerializedName("t") val translation: String = "",
    @SerializedName("y") val transliteration: String = "",
    @SerializedName("j") val tajweed: String = "",
    @SerializedName("e") val end: Int = 0
)

/**
 * Word data source for the reader and Mushaf view.
 *
 * - [wordsForChapter] / [wordsForVerse] read the bundled word-by-word dataset
 *   (`data/words/{chapter}.json`, generated by `tools/generate_word_data.py`),
 *   so word tooltips work fully offline.
 * - [getPageWords] keeps the Android-compatible page layout request
 *   (`GET /verses/by_page/{page}`, Madani Standard) for the Mushaf view:
 *   cache-first at `~/.quran-nur/words/page_{n}.json`, network on miss.
 */
object WordStore {
    private const val BASE_URL = "https://api.quran.com/api/v4"
    private const val WORD_FIELDS =
        "text_qpc_hafs,text_uthmani,page_number,line_number,translation,text_uthmani_tajweed"
    private const val MUSHAF_ID = 5 // Madani Standard (Android default)
    private const val PER_PAGE = 50

    private val gson = Gson()

    private val chapterCache = mutableMapOf<Int, Map<String, List<VerseWord>>>()

    private fun cacheFile(page: Int): File {
        val dir = File(System.getProperty("user.home"), ".quran-nur/words")
        return File(dir, "page_$page.json")
    }

    /**
     * All words of every verse in [chapter], keyed by verse key (`"2:255"`).
     * Returns an empty map when the chapter is out of range or unreadable.
     */
    @Synchronized
    fun wordsForChapter(chapter: Int): Map<String, List<VerseWord>> {
        if (chapter !in 1..114) return emptyMap()
        chapterCache[chapter]?.let { return it }
        val raw = try {
            WordStore::class.java.getResourceAsStream("/data/words/$chapter.json")
                ?.bufferedReader(Charsets.UTF_8)
                ?.use { it.readText() }
        } catch (_: Exception) {
            null
        }
        if (raw.isNullOrBlank()) return emptyMap()
        val parsed = try {
            gson.fromJson(raw, Array<BundledVerseJson>::class.java)?.toList().orEmpty()
        } catch (_: Exception) {
            emptyList()
        }
        val map = parsed.associate { verse ->
            val words = verse.words.orEmpty().mapIndexed { index, word ->
                VerseWord(
                    verseKey = verse.key,
                    position = index + 1,
                    arabic = word.arabic,
                    translation = word.translation,
                    transliteration = word.transliteration,
                    tajweedHtml = word.tajweed,
                    isEndMarker = word.end == 1
                )
            }
            verse.key to words
        }
        chapterCache[chapter] = map
        return map
    }

    /** Bundled words for a single verse key (`"18:10"`), or empty when unknown. */
    fun wordsForVerse(verseKey: String): List<VerseWord> {
        val chapter = verseKey.substringBefore(":").toIntOrNull() ?: return emptyList()
        return wordsForChapter(chapter)[verseKey].orEmpty()
    }

    fun getPageWords(page: Int): List<PageWord> {
        if (page !in 1..604) return emptyList()
        val file = cacheFile(page)
        // Cache first.
        try {
            if (file.exists()) {
                val raw = file.readText(Charsets.UTF_8)
                if (raw.isNotBlank()) return parse(raw)
            }
        } catch (_: Exception) {
            // Fall through to network.
        }
        // Network on miss.
        val raw = try {
            fetch(page)
        } catch (_: Exception) {
            return emptyList()
        }
        try {
            file.parentFile?.mkdirs()
            file.writeText(raw, Charsets.UTF_8)
        } catch (_: Exception) {
            // Cache write is best-effort.
        }
        return try {
            parse(raw)
        } catch (_: Exception) {
            emptyList()
        }
    }

    private fun fetch(page: Int): String {
        val url = URL(
            "$BASE_URL/verses/by_page/$page" +
                "?words=true&word_fields=$WORD_FIELDS&mushaf=$MUSHAF_ID&per_page=$PER_PAGE"
        )
        val conn = (url.openConnection() as HttpURLConnection).apply {
            connectTimeout = 10_000
            readTimeout = 10_000
            setRequestProperty("User-Agent", "quran-desktop-kotlin/1.0 (desktop)")
            setRequestProperty("Accept", "application/json")
        }
        try {
            if (conn.responseCode != HttpURLConnection.HTTP_OK) {
                throw IllegalStateException("HTTP ${conn.responseCode}")
            }
            return conn.inputStream.bufferedReader(Charsets.UTF_8).use { it.readText() }
        } finally {
            conn.disconnect()
        }
    }

    private fun parse(raw: String): List<PageWord> {
        if (raw.isBlank()) return emptyList()
        val res = gson.fromJson(raw, PageWordsResponse::class.java) ?: return emptyList()
        return res.verses.orEmpty().flatMap { verse ->
            verse.words.orEmpty().mapNotNull { word ->
                val text = word.textUthmani?.takeIf { it.isNotBlank() }
                    ?: word.textQpcHafs?.takeIf { it.isNotBlank() }
                    ?: word.textIndopak?.takeIf { it.isNotBlank() }
                    ?: return@mapNotNull null
                PageWord(
                    verseKey = verse.verseKey,
                    text = text,
                    lineNumber = word.lineNumber ?: 0,
                    translation = word.translation?.text.orEmpty()
                )
            }
        }
    }
}
